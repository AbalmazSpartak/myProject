import Foundation

/// Подписка. Создавать темы и писать в обсуждениях — только с ней; читать, оценивать и ставить «нравится» — всем.
/// Покупки пока нет: доступ открыт всем. В «Разделе разработчика» можно изобразить «без подписки» —
/// посмотреть, как выглядят закрытые места. Настоящая проверка (StoreKit) встанет сюда же
enum Subscription {
    /// Только для проверки вида без подписки (Раздел разработчика)
    static let simulateMissingKey = "debug_simulate_no_subscription"

    static func canPost(simulatingMissing: Bool) -> Bool {
        !simulatingMissing
    }

    static let lockedMessage = "Создавать темы и писать в обсуждениях можно с подпиской. Читать, оценивать и отмечать «нравится» можно всем."
}
